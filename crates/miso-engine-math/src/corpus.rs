//! The cross-target determinism corpus behind gate M3.
//!
//! Each case is one function evaluated over a fixed, seed-generated million-point input set. The
//! inputs are produced by integer arithmetic and exact conversions only, so every target builds an
//! identical input sequence; the outputs are therefore a pure function of the vendored scalar
//! layer. `tests/m3_determinism.rs` hashes each case's output words and compares them against
//! [`M3_DIGESTS`], and job 83d replays the same cases under wasmtime against the same pins.
//!
//! **Sampling.** A uniformly random `f64` *bit pattern* has a uniformly random exponent, so it is
//! almost always astronomically large or astronomically small. A corpus built that way would feed
//! `exp2` nothing but its overflow and underflow early-outs and would not notice a wrong
//! polynomial coefficient at all (measured: a corpus of raw bit patterns misses a one-ulp change
//! to `exp2`'s leading coefficient entirely). Each case therefore samples the domain where its
//! function does real work, while every fourth point stays a raw finite bit pattern so subnormals,
//! the representable extremes and huge trig arguments remain covered.
//!
//! **No NaN.** The determinism claim (master plan D5) excludes NaN payloads because wasm
//! canonicalises them, so the input filters keep every case NaN-free: `log`-family inputs are
//! non-negative, `pow` bases are positive, and every other function maps finite inputs to non-NaN
//! results. `tests/m3_determinism.rs::m3_corpus_is_nan_free` is the guard.
//!
//! The pinned digests are a regression guard, not an oracle. They were generated by this layer on
//! x86_64; correctness of the layer itself is what `tests/scalar_accuracy.rs` proves.

