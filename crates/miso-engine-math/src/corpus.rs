/// xorshift64\* state. Integer-only, so identical on every target.
struct Rng(u64);

impl Rng {
    fn new(case: usize) -> Self {
        // Any odd seed works; mixing the case index keeps the cases independent.
        Self(0x9e37_79b9_7f4a_7c15 ^ ((case as u64).wrapping_mul(0x0002_5a2f_1c3d_0b41) | 1))
    }

    fn next(&mut self) -> u64 {
        let mut x = self.0;
        x ^= x >> 12;
        x ^= x << 25;
        x ^= x >> 27;
        self.0 = x;
        x.wrapping_mul(0x2545_f491_4f6c_dd1d)
    }
}

/// Finite `f64` from arbitrary bits: an infinite or NaN exponent field is pulled down one bit.
fn finite_f64(bits: u64) -> f64 {
    let bits = if (bits >> 52) & 0x7ff == 0x7ff {
        bits & !(1u64 << 62)
    } else {
        bits
    };
    f64::from_bits(bits)
}

/// Edge inputs prepended to every case, before the generated points.
const EDGE: [f64; 16] = [
    0.0,
    -0.0,
    1.0,
    -1.0,
    0.5,
    -0.5,
    2.0,
    -2.0,
    f64::MIN_POSITIVE,
    -f64::MIN_POSITIVE,
    f64::MAX,
    f64::MIN,
    core::f64::consts::PI,
    core::f64::consts::FRAC_PI_2,
    core::f64::consts::E,
    core::f64::consts::LN_2,
];

/// Whether case `case` is an `f32` case (its result words are `f32::to_bits` widened to `u64`).
fn is_f32_case(case: usize) -> bool {
    matches!(case, 13..=23 | 25 | 27 | 30 | 31)
}

/// The `f64` case a case shares its input domain with; the `f32` cases mirror their `f64`
/// counterparts so both halves of the corpus cover the same shapes.
fn domain_of(case: usize) -> usize {
    match case {
        13..=23 => case - 13,
        25 => 24,
        27 => 26,
        30 => 28,
        31 => 29,
        other => other,
    }
}

/// Uniform `[0, 1)` from a bit pattern. Converting a 53-bit integer to `f64` is exact, so this is
/// the same value on every target.
fn unit(bits: u64) -> f64 {
    ((bits >> 11) as f64) / 9_007_199_254_740_992.0
}

/// `2^k` built straight from the exponent field, so the input sampler never calls the layer whose
/// outputs it is generating. `k` is truncated from `n`.
fn pow2(n: f64) -> f64 {
    let k = n as i32;
    if k >= -1022 {
        f64::from_bits(((k + 1023) as u64) << 52)
    } else {
        let shift = (-1022 - k) as u32;
        if shift > 52 {
            0.0
        } else {
            f64::from_bits(1u64 << (52 - shift))
        }
    }
}

/// One input for `case`, from two uniform deviates. See the module note on sampling.
///
/// `narrow` selects the `f32` variant of the domain: `expf` saturates at about +/-88 where `exp`
/// runs to +/-709, so sharing one range would push nine tenths of the `f32` points into the
/// saturation branches.
fn domain_sample(case: usize, narrow: bool, u: f64, v: f64) -> f64 {
    // Log-uniform over a range of binades, with a full mantissa: `pow2` alone would yield only a
    // few hundred distinct inputs.
    let log_uniform = |lo: f64, span: f64| pow2(lo + u * span) * (1.0 + v);

    match domain_of(case) {
        // exp: the whole non-trivial range, a little past both saturation thresholds.
        0 if narrow => -100.0 + u * 195.0,
        0 => -760.0 + u * 1480.0,
        // exp2
        1 if narrow => -155.0 + u * 290.0,
        1 => -1090.0 + u * 2130.0,
        // expm1: past the point where the result is just `exp(x)` or `-1`.
        2 if narrow => -20.0 + u * 110.0,
        2 => -40.0 + u * 750.0,
        // log, log2, log10, sqrt, gain_to_db: log-uniform over the positive range.
        3..=5 | 24 | 29 if narrow => log_uniform(-150.0, 278.0),
        3..=5 | 24 | 29 => log_uniform(-1070.0, 2093.0),
        // pow / powf: `eval` uses one draw as the base and one as the exponent.
        6 if narrow => -30.0 + u * 60.0,
        6 => -40.0 + u * 80.0,
        // sin, cos, tan: a few hundred radians, the medium argument-reduction path.
        7..=9 => -200.0 + u * 400.0,
        // tanh: `f32` cannot resolve neighbouring results much past +/-3 (the spacing of `f32`
        // near 1 is 6e-8 and tanh's slope there is 1e-2), so the narrow domain stops there and
        // the raw-bit quarter of the corpus covers saturation.
        10 if narrow => -3.0 + u * 6.0,
        10 => -19.0 + u * 38.0,
        // atan, atan2
        11 | 12 => -50.0 + u * 100.0,
        // floor
        26 if narrow => -1.0e6 + u * 2.0e6,
        26 => -1.0e7 + u * 2.0e7,
        // db_to_gain: the dB range a mixer actually uses, widened past both rails.
        28 if narrow => -160.0 + u * 200.0,
        28 => -400.0 + u * 500.0,
        _ => unreachable!(),
    }
}

/// Narrow to `f32`, saturating to the largest finite `f32` rather than to an infinity.
///
/// Without this, an `f64` edge value such as `f64::MAX` would become `f32::INFINITY`, and
/// `sinf(inf)` is NaN, which the corpus must not contain.
fn narrow_finite(x: f64) -> f32 {
    let v = x as f32;
    if v.is_finite() {
        v
    } else if v > 0.0 {
        f32::MAX
    } else {
        f32::MIN
    }
}

/// Run corpus case `case`, writing one result word per input into `out`.
///
/// `f64` results are stored as `f64::to_bits`, `f32` results as `f32::to_bits` widened to `u64`.
///
/// # Panics
///
/// Panics if `case >= CASE_COUNT` or `out.len() != POINTS`.
pub fn run_case(case: usize, out: &mut [u64]) {
    assert!(case < CASE_COUNT, "corpus case out of range");
    assert_eq!(
        out.len(),
        POINTS,
        "corpus output buffer must hold POINTS words"
    );

    let mut rng = Rng::new(case);
    let narrow = is_f32_case(case);

    for (index, slot) in out.iter_mut().enumerate() {
        // Four draws per point regardless of arity, so every case walks the generator in lockstep.
        let a = rng.next();
        let b = rng.next();
        let c = rng.next();
        let d = rng.next();

        let (mut x, mut y) = if index < EDGE.len() {
            (EDGE[index], EDGE[EDGE.len() - 1 - index])
        } else if index % 4 == 0 {
            // Raw finite bit patterns: subnormals, the extremes, huge trig arguments.
            (finite_f64(a), finite_f64(c))
        } else {
            (
                domain_sample(case, narrow, unit(a), unit(b)),
                domain_sample(case, narrow, unit(c), unit(d)),
            )
        };

        if narrow {
            x = f64::from(narrow_finite(x));
            y = f64::from(narrow_finite(y));
        }

        *slot = eval(case, x, y);
    }
}

/// Evaluate one corpus point. `x` is the primary input, `y` the second argument of the two-argument
/// cases; `f32` cases narrow both back to `f32` before calling.
fn eval(case: usize, x: f64, y: f64) -> u64 {
    let xf = x as f32;
    let yf = y as f32;
    match case {
        0 => exp(x).to_bits(),
        1 => exp2(x).to_bits(),
        2 => expm1(x).to_bits(),
        3 => log(x.abs()).to_bits(),
        4 => log2(x.abs()).to_bits(),
        5 => log10(x.abs()).to_bits(),
        // A strictly positive base keeps `pow` NaN-free for every finite exponent.
        6 => pow(x.abs() + f64::MIN_POSITIVE, y * 0.5).to_bits(),
        7 => sin(x).to_bits(),
        8 => cos(x).to_bits(),
        9 => tan(x).to_bits(),
        10 => tanh(x).to_bits(),
        11 => atan(x).to_bits(),
        12 => atan2(x, y).to_bits(),
        13 => u64::from(expf(xf).to_bits()),
        14 => u64::from(exp2f(xf).to_bits()),
        15 => u64::from(expm1f(xf).to_bits()),
        16 => u64::from(logf(xf.abs()).to_bits()),
        17 => u64::from(log2f(xf.abs()).to_bits()),
        18 => u64::from(log10f(xf.abs()).to_bits()),
        19 => u64::from(powf(xf.abs() + f32::MIN_POSITIVE, yf * 0.5).to_bits()),
        20 => u64::from(sinf(xf).to_bits()),
        21 => u64::from(cosf(xf).to_bits()),
        22 => u64::from(tanf(xf).to_bits()),
        23 => u64::from(tanhf(xf).to_bits()),
        24 => sqrt(x.abs()).to_bits(),
        25 => u64::from(sqrtf(xf.abs()).to_bits()),
        26 => floor(x).to_bits(),
        27 => u64::from(floorf(xf).to_bits()),
        28 => db_to_gain(x).to_bits(),
        29 => gain_to_db(x.abs()).to_bits(),
        30 => u64::from(db_to_gain_f32(xf).to_bits()),
        31 => u64::from(gain_to_db_f32(xf.abs()).to_bits()),
        _ => unreachable!(),
    }
}

