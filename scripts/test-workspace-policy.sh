create_valid_fixture() {
    local fixture_root="$1"
    mkdir -p \
        "$fixture_root/crates/library/src" \
        "$fixture_root/crates/math" \
        "$fixture_root/fuzz" \
        "$fixture_root/hosts/binary/src" \
        "$fixture_root/tools"

    cp "$script_directory/../LICENSE" "$fixture_root/LICENSE"
    printf '%s\n' 'Miso Engine' >"$fixture_root/NOTICE"
    printf '%s\n' 'See crates/math/LICENSE-libm.txt.' >"$fixture_root/THIRD_PARTY_LICENSES.md"
    printf '%s\n' 'fixture third-party license' >"$fixture_root/crates/math/LICENSE-libm.txt"
    printf '%s\n' \
        '[workspace.package]' \
        'license = "FSL-1.1-ALv2"' \
        >"$fixture_root/Cargo.toml"
    printf '%s\n' \
        '[package]' \
        'name = "session-fuzz"' \
        'license = "FSL-1.1-ALv2"' \
        >"$fixture_root/fuzz/Cargo.toml"
    # A minimal, cargo-free lockfile so the retired-delivery-codec lockfile scan has a fixed
    # target; its exact contents do not matter, only that it exists and names no retired crate.
    printf '%s\n' \
        '# This file is automatically @generated by Cargo.' \
        '# It is not intended for manual editing.' \
        'version = 4' \
        >"$fixture_root/Cargo.lock"

    printf '%s\n' \
        '[package]' \
        'name = "library"' \
        'license.workspace = true' \
        '' \
        '[lib]' \
        'name = "library"' \
        '' \
        '[features]' \
        'default = []' \
        >"$fixture_root/crates/library/Cargo.toml"
    printf '//! fixture\n' >"$fixture_root/crates/library/src/lib.rs"

    printf '%s\n' \
        '[package]' \
        'name = "binary"' \
        'license.workspace = true' \
        '' \
        '[[bin]]' \
        'name = "binary"' \
        'path = "src/main.rs"' \
        '' \
        '[features]' \
        'default = []' \
        >"$fixture_root/hosts/binary/Cargo.toml"
    printf 'fn main() {}\n' >"$fixture_root/hosts/binary/src/main.rs"
    materialize_source_scrape_allowance "$fixture_root"
}

# #1052: the policy under test allows each pre-existing source scrape exactly, per file and
# literal path, so a valid tree holds exactly that many reads of each. The rows are read from the
# policy itself, so the fixture follows every row an owning issue lowers or deletes. Each file is
# truncated first, so re-creating a fixture root does not double its reads.
materialize_source_scrape_allowance() {
    local fixture_root="$1" rows count file path _owner directories=()
    rows="$(sed -n "/^source_scrape_allowlist='\$/,/^'\$/p" "$policy_script")"
    while read -r count file path _owner; do
        [[ -n "$path" ]] && directories+=("$fixture_root/${file%/*}")
    done <<<"$rows"
    (( ${#directories[@]} == 0 )) || mkdir -p "${directories[@]}"
    while read -r count file path _owner; do
        [[ -n "$path" ]] && : >"$fixture_root/$file"
    done <<<"$rows"
    while read -r count file path _owner; do
        [[ -n "$path" ]] || continue
        for ((; count > 0; count--)); do
            printf 'const _: &str = include_str!("%s");\n' "$path" >>"$fixture_root/$file"
        done
    done <<<"$rows"
}

expect_failure() {
    local fixture_name="$1"
    local fixture_root="$scratch_root/$fixture_name"
    shift
    create_valid_fixture "$fixture_root"
    "$@" "$fixture_root"

    if bash "$policy_script" "$fixture_root" >/dev/null 2>&1; then
        printf 'policy mutation unexpectedly passed: %s\n' "$fixture_name" >&2
        exit 1
    fi
}

# N20: like expect_failure, but also asserts the failure message contains the given substring --
# proving the mutation was caught by the rule it targets, not by some unrelated failure that
# happens to also reject the fixture.
expect_failure_with_message() {
    local fixture_name="$1" expected_substring="$2"
    local fixture_root="$scratch_root/$fixture_name"
    shift 2
    create_valid_fixture "$fixture_root"
    "$@" "$fixture_root"

    local output
    if output="$(bash "$policy_script" "$fixture_root" 2>&1)"; then
        printf 'policy mutation unexpectedly passed: %s\n' "$fixture_name" >&2
        exit 1
    fi
    if [[ "$output" != *"$expected_substring"* ]]; then
        printf 'policy mutation %s failed for the wrong reason (expected to contain %q): %s\n' \
            "$fixture_name" "$expected_substring" "$output" >&2
        exit 1
    fi
}

# Like expect_failure_with_message, but every row must appear: one run proves several planted
# violations are each caught, so none can hide behind another.
expect_failure_with_rows() {
    local fixture_name="$1" mutation="$2"
    local fixture_root="$scratch_root/$fixture_name" output row
    shift 2
    create_valid_fixture "$fixture_root"
    "$mutation" "$fixture_root"
    if output="$(bash "$policy_script" "$fixture_root" 2>&1)"; then
        printf 'policy mutation unexpectedly passed: %s\n' "$fixture_name" >&2
        exit 1
    fi
    for row in "$@"; do
        [[ "$output" == *"$row"* ]] || {
            printf 'policy mutation %s did not report %q: %s\n' "$fixture_name" "$row" "$output" >&2
            exit 1
        }
    done
}

